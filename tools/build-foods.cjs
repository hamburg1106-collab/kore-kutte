function num(v) {
  // 「(11.3)」は推定値、「Tr」は微量、「-」は未測定。どれも数字として扱える形にする
  const s = String(v).replace(/[()（）]/g, "").trim();
  if (s === "" || s === "-" || s === "*" || /^Tr$/i.test(s)) return 0;
  const n = Number(s);
  return isFinite(n) ? n : 0;
}

const r1 = (n) => Math.round(n * 10) / 10;

/* 表示用の名前。「＜鳥肉類＞」のような分類の見出しを外し、かっこと空白を整える */
function cleanName(s) {
  return String(s)
    .replace(/＜[^＞]*＞/g, "")
    .replace(/[［］（）]/g, " ")
    .replace(/[　\s]+/g, " ")
    .trim();
}

const file = process.argv[2];
if (!file) {
  console.error("Excelのパスを指定してください");
  process.exit(1);
}

const wb = X.readFile(file);
const rows = X.utils
  .sheet_to_json(wb.Sheets["表全体"], { header: 1, defval: "" })
  .filter((r) => /^\d{5}$/.test(String(r[COL.num])));

const byNum = new Map();
const table = rows.map((r) => {
  const item = {
    name: cleanName(r[COL.name]),
    kcal: num(r[COL.kcal]),
    protein: num(r[COL.protein]),
    fat: num(r[COL.fat]),
    carbs: num(r[COL.carbs]),
  };
  byNum.set(String(r[COL.num]), item);
  return [item.name, item.kcal, r1(item.protein), r1(item.fat), r1(item.carbs)];
});

const common = COMMON.map(([name, unit, parts]) => {
  const sum = { kcal: 0, protein: 0, fat: 0, carbs: 0 };
  parts.forEach(([n, g]) => {
    const f = byNum.get(n);
    if (!f) throw new Error("成分表に無い食品番号です: " + n + "（" + name + "）");
    Object.keys(sum).forEach((k) => (sum[k] += (f[k] * g) / 100));
  });
  return [name, unit, Math.round(sum.kcal), r1(sum.protein), r1(sum.fat), r1(sum.carbs)];
});

/* 献立は画面を開いてすぐ使うので、小さな別ファイルにする（foods.json は検索するまで読まない） */
const commonByName = new Map(common.map((c) => [c[0] + "|" + c[1], c]));
const commonFirst = new Map();
common.forEach((c) => commonFirst.has(c[0]) || commonFirst.set(c[0], c));

const menus = MENUS.map(([name, place, slots, parts]) => {
  const sum = [0, 0, 0, 0];
  parts.forEach(([n, count]) => {
    const c = commonByName.get(n) || commonFirst.get(n);
    if (!c) throw new Error("献立に使った呼び名が COMMON にありません: " + n + "（" + name + "）");
    for (let i = 0; i < 4; i++) sum[i] += c[i + 2] * count;
  });
  return [name, place, slots, Math.round(sum[0]), r1(sum[1]), r1(sum[2]), r1(sum[3])];
});

const dir = path.join(__dirname, "..", "src", "data");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "foods.json"), JSON.stringify({ source: SOURCE, common, table }));
fs.writeFileSync(path.join(dir, "menus.json"), JSON.stringify(menus));
